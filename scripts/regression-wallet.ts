import {runVendorRegressions} from './regression-wallet-vendor';
import {hashPassword} from '../src/lib/auth';
import {issueWalletChallenge} from '../src/lib/wallet/security';
import {resetRateLimit} from '../src/lib/rate-limiter';
import {runWalletExecutionRegressions} from './regression-wallet-execution';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { prisma } from '../src/lib/prisma';
import {createFundedEnvelope,fundingState,minorUnits,readOwnWallet,readFundingDashboard,walletTransaction} from '../src/lib/wallet/core';
import {approveWalletRelease,stageWalletRelease} from '../src/lib/wallet/releases';
import { providerAmountMinor } from '../src/lib/wallet/monnify-balance';
if (new URL(process.env.DATABASE_URL || '').pathname !== '/bems_corrections_test') throw new Error('Wallet tests require the isolated bems_corrections_test database.');
if (!new URL(process.env.DATABASE_URL!).searchParams.get('schema')?.startsWith('wallet_regression_')) throw new Error('Use the isolated wallet schema runner.');
process.env.BEMS_WALLET_ENABLED = 'true';
process.env.BEMS_WALLET_AUTO_REFRESH = 'false';
process.env.BEMS_WALLET_MAX_TRANSFER_FEE_MINOR='1000';
process.env.MONNIFY_ENVIRONMENT = 'sandbox';
process.env.MONNIFY_SOURCE_ACCOUNT = '9999999999';
const suffix = randomUUID();
async function main() {
  // This test owns the global fixture and must run serially, in the dedicated test DB.
  const prior = await prisma.employee.findFirst({ where: { role: 'GMD', status: 'ACTIVE', approvalStatus: 'APPROVED' } });
  assert.equal(prior, null, 'Use a clean isolated GMD fixture.');
  const password='Isolated-wallet-only-123!';const passwordHash=await hashPassword(password);
  const admin = await prisma.employee.create({ data: { employeeNumber: 'WA-' + suffix, legalName: 'Wallet Admin', workEmail: 'wa-' + suffix + '@example.invalid', role: 'SUPER_ADMIN', status: 'ACTIVE', approvalStatus: 'APPROVED' } });
  const gmd = await prisma.employee.create({ data: { employeeNumber: 'WG-' + suffix, legalName: 'Wallet GMD', workEmail: 'wg-' + suffix + '@example.invalid', passwordHash, role: 'GMD', status: 'ACTIVE', approvalStatus: 'APPROVED' } });
  const staff = await prisma.employee.create({ data: { employeeNumber: 'WS-' + suffix, legalName: 'Wallet Staff', workEmail: 'ws-' + suffix + '@example.invalid', passwordHash, role: 'STAFF', status: 'ACTIVE', approvalStatus: 'APPROVED' } });
  const other = await prisma.employee.create({ data: { employeeNumber: 'WO-' + suffix, legalName: 'Other Staff', workEmail: 'wo-' + suffix + '@example.invalid', passwordHash, role: 'STAFF', status: 'ACTIVE', approvalStatus: 'APPROVED' } });
  process.env.BEMS_FINANCIAL_GMD_ID = gmd.id;
  const org = await prisma.organization.create({ data: { type: 'SUBSIDIARY', code: 'W-' + suffix, legalName: 'Wallet test subsidiary' } });
  await prisma.$executeRaw`INSERT INTO "WalletFundingPool" ("id","environment","sourceAccount","availableMinor","feeReserveMinor","observedAt","observationId","paused") VALUES ('MONNIFY_NGN','sandbox','9999999999',1000000,10000,now(),${suffix},false)`;
  assert.equal(providerAmountMinor('1234.56'), BigInt(123456));
  assert.throws(() => providerAmountMinor('1.001'));
  assert.throws(() => minorUnits('1.2'));
  assert.throws(() => minorUnits('-1'));
  console.log('PASS exact money parsing rejects fractions of kobo and invalid values');
  const allocate = (key: string) => createFundedEnvelope(admin, { organizationId: org.id, label: 'Test funded envelope', amountMinor: '600000', idempotencyKey: key });
  const allocations = await Promise.allSettled([allocate('A-' + suffix), allocate('B-' + suffix)]);
  assert.equal(allocations.filter(x => x.status === 'fulfilled').length, 1);
  const envelope = (allocations.find(x => x.status === 'fulfilled') as PromiseFulfilledResult<any>).value;
  console.log('PASS concurrent budgets cannot promise the same central funding twice');
  const key = allocations[0].status === 'fulfilled' ? 'A-' + suffix : 'B-' + suffix;
  assert.equal((await allocate(key)).id, envelope.id);
  await assert.rejects(createFundedEnvelope(staff, { organizationId: org.id, label: 'Unauthorized', amountMinor: '1', idempotencyKey: suffix }));
  console.log('PASS budget idempotency and staff authorization are enforced');
  const secureApprove=async(p:any)=>{await resetRateLimit('wallet-password:'+gmd.id);const proof=await issueWalletChallenge(gmd,{purpose:'RELEASE',payload:{id:p.id,confirmationHash:p.confirmationHash},password,sessionHash:'isolated-session'});return approveWalletRelease(gmd,p.id,p.confirmationHash,{...proof,sessionHash:'isolated-session'});};
  const createRequest = (name: string, amount = BigInt(400000)) => prisma.expenditureRequest.create({ data: { requestNumber: name + suffix, groupId: org.id, subsidiaryId: org.id, requestedById: staff.id, amountMinor: amount, title: name, justification: 'Wallet isolated regression', deliverable: 'Evidence', neededBy: new Date(), category: 'OFFICE_EXPENSE' } });
  const first = await createRequest('FIRST');
  const second = await createRequest('SECOND');
  const stage = (sourceId: string) => stageWalletRelease(admin, { sourceType: 'REQUEST', sourceId, envelopeId: envelope.id });
  const [p1,p2] = await Promise.all([stage(first.id),stage(second.id)]);
  await assert.rejects(approveWalletRelease(admin, p1.id, p1.confirmationHash), /Only the designated GMD/);
  await assert.rejects(approveWalletRelease(staff, p1.id, p1.confirmationHash), /Only the designated GMD/);
  await assert.rejects(approveWalletRelease(gmd, p1.id, '0'.repeat(64)), /exact stored preview/);
  assert.equal((await readOwnWallet(staff)).availableMinor, '0');
  console.log('PASS direct non-GMD approval and forged preview cannot create wallet funds');
  await prisma.$executeRaw`UPDATE "WalletFundingPool" SET "availableMinor"=610000 WHERE "id"='MONNIFY_NGN'`;
  await assert.rejects(secureApprove(p1),/Fund company fees/);
  assert.equal((await readOwnWallet(staff)).availableMinor,'0');
  await prisma.$executeRaw`UPDATE "WalletFundingPool" SET "availableMinor"=1000000,"observedAt"=now() WHERE "id"='MONNIFY_NGN'`;
  console.log('PASS GMD cannot release principal when company withdrawal fees lack backing');
  const releases = await Promise.allSettled([secureApprove(p1),secureApprove(p2)]);
  assert.equal(releases.filter(x => x.status === 'fulfilled').length, 1);
  const successful = releases[0].status === 'fulfilled' ? p1 : p2;
  const credit = await approveWalletRelease(gmd, successful.id, successful.confirmationHash);
  assert.equal(credit.alreadyExecuted, true);
  assert.equal((await readOwnWallet(staff)).availableMinor, '400000');
  assert.equal((await readOwnWallet(other)).availableMinor, '0');
  const funding = await walletTransaction(tx => fundingState(tx));
  assert.equal(funding.envelopeMinor, BigInt(200000));
  assert.equal(funding.liabilityMinor, BigInt(400000));
  assert.equal(funding.freeMinor, BigInt(360000));
  console.log('PASS concurrent releases respect envelope capacity, credit once and never expose another staff wallet');
  const changed = await createRequest('CHANGED',BigInt(10));
  const stale = await stage(changed.id);
  await prisma.expenditureRequest.update({ where: { id: changed.id }, data: { amountMinor: BigInt(20), requestVersion: { increment: 1 } } });
  await assert.rejects(secureApprove(stale), /source changed/i);
  await prisma.employee.update({ where: { id: gmd.id }, data: { status: 'SUSPENDED' } });
  await assert.rejects(approveWalletRelease(gmd,successful.id,successful.confirmationHash), /no longer authorized/);
  await prisma.employee.update({ where: { id: gmd.id }, data: { status: 'ACTIVE' } });
  console.log('PASS stale sources and revoked GMD sessions cannot execute proposals');
  await prisma.$executeRaw`UPDATE "WalletFundingPool" SET "observedAt" = now() - interval '2 minutes' WHERE "id" = 'MONNIFY_NGN'`;
  await assert.rejects(createFundedEnvelope(admin,{ organizationId: org.id,label: 'Stale',amountMinor:'1',idempotencyKey:'STALE-'+suffix }), /Refresh the verified/);
  await prisma.$executeRaw`UPDATE "WalletFundingPool" SET "observedAt" = now(), "availableMinor" = 1 WHERE "id" = 'MONNIFY_NGN'`;
  await assert.rejects(createFundedEnvelope(admin,{ organizationId: org.id,label: 'Deficit',amountMinor:'1',idempotencyKey:'DEFICIT-'+suffix }), /exceed verified funding/);
  console.log('PASS stale provider evidence and funding deficits stop new commitments');
  await assert.rejects(prisma.$transaction(async tx => {
    const id=randomUUID();
    await tx.$executeRaw`INSERT INTO "WalletJournal" ("id","kind","reference","actorId") VALUES (${id},'WALLET_CREDITED',${id},${gmd.id})`;
    await tx.$executeRaw`INSERT INTO "WalletJournalEntry" ("id","journalId","accountKey","amountMinor") VALUES (${randomUUID()},${id},'INVALID',1)`;
  }), /balanced entries/);
  await assert.rejects(prisma.$executeRaw`UPDATE "WalletJournalEntry" SET "amountMinor" = 1` , /immutable/);
  const [posted] = await prisma.$queryRaw<Array<{id:string}>>`SELECT "id" FROM "WalletJournal" LIMIT 1`;
  await assert.rejects(prisma.$transaction(async tx => {
    await tx.$executeRaw`INSERT INTO "WalletJournalEntry" ("id","journalId","accountKey","amountMinor") VALUES (${randomUUID()},${posted.id},'LATE',1),(${randomUUID()},${posted.id},'LATE',-1)`;
  }), /Cannot append entries/);
  console.log('PASS PostgreSQL rejects unbalanced and edited posted journals');
  await runWalletExecutionRegressions({admin,gmd,staff,other,org,envelope,secureApprove,password});
  await prisma.$executeRaw`UPDATE "WalletFundingPool" SET "observedAt"=now(),"paused"=false WHERE "id"='MONNIFY_NGN'`;
  await runVendorRegressions({admin,gmd,staff,other,org,envelope,secureApprove,password});
  process.env.BEMS_WALLET_ENABLED='false';
  try {
    const own=await readOwnWallet(staff);assert.equal(own.walletMode,false);assert.equal(own.withdrawalsEnabled,false);
    const review=await readFundingDashboard(gmd);assert.equal(review.walletMode,false);assert.equal(review.canApprove,false);
    await assert.rejects(readFundingDashboard(staff),{code:'NOT_PERMITTED'});
    await assert.rejects(readOwnWallet(gmd),{code:'STAFF_WALLET_REQUIRED'});
    await assert.rejects(createFundedEnvelope(gmd,{organizationId:org.id,label:'Disabled review cannot allocate',amountMinor:'1',idempotencyKey:randomUUID()}),{code:'WALLET_NOT_ENABLED'});
    console.log('PASS disabled wallet mode permits authorized read-only review while funding writes and staff executive access remain blocked');
  } finally {process.env.BEMS_WALLET_ENABLED='true';}
  // Immutable journals retain fixtures for forensic inspection. End the active GMD fixture.
  await prisma.employee.update({ where: { id: gmd.id }, data: { status: 'TERMINATED' } });
  console.log('Wallet foundation regressions passed. No provider network call or real transfer was made.');
}
main().catch(e => { console.error(e); process.exitCode=1; }).finally(() => prisma.$disconnect());
